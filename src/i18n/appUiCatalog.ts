/** Deep-merge catalogue namespaces onto a dictionary (one nested level for groups like tasks). */
export function mergeAppUi(dict, ui) {
  if (!ui) return dict;
  const out = { ...dict };
  for (const [ns, values] of Object.entries(ui)) {
    if (values && typeof values === 'object' && !Array.isArray(values)) {
      const base = dict[ns] && typeof dict[ns] === 'object' ? dict[ns] : {};
      const merged = { ...base, ...values };
      for (const [k, v] of Object.entries(values)) {
        if (v && typeof v === 'object' && !Array.isArray(v) && base[k] && typeof base[k] === 'object') {
          merged[k] = { ...base[k], ...v };
        }
      }
      out[ns] = merged;
    } else {
      out[ns] = values;
    }
  }
  return out;
}
