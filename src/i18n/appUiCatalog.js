/** Deep-merge catalogue namespaces onto a dictionary. */
export function mergeAppUi(dict, ui) {
  if (!ui) return dict;
  const out = { ...dict };
  for (const [ns, values] of Object.entries(ui)) {
    if (values && typeof values === 'object' && !Array.isArray(values)) {
      out[ns] = { ...(dict[ns] || {}), ...values };
    } else {
      out[ns] = values;
    }
  }
  return out;
}
